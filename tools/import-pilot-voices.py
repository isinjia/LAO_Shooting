"""Pilot battle voice lines (original voice acting) -> assets/audio/voice/*.ogg + js/pilot-voices.js.

The skill / death `char_XX` clips on the animations are effect mixes; the spoken lines live in
Sounds/Voice/<character>/Voice_<code>_<Slot>.mp3. Each pilot's battle set is mapped to game
moments (js/game.js / js/main.js):
  sortie     SortiePick     select-screen confirm
  stageStart StageStart     each stage's start card
  special    ActionApprove  C cast
  bomb       SpSkill        X cast (and deathbomb)
  warning    BattleFocus    midboss / boss WARNING
  miss       Retreat        a life lost
  gameover   Retire         last life lost
  clear      MVP            stage clear
Lines are trimmed (leading silence), loudness-matched (-15 dB RMS, loudest 300 ms) with a
-1.5 dBFS peak ceiling, mono ogg.
usage: python tools/import-pilot-voices.py
"""
import json
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sfx_analyze import SR, decode, measure  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = Path("E:/LAO/Google_QA/Assets/AssetBundleResource/Sounds/Voice")
OUT = ROOT / "assets" / "audio" / "voice"
TARGET = -15.0

PILOTS = {  # game key -> (Voice folder, file prefix)
    "griffin": ("PA00EL", None),
    "sleipnir": ("Sleipnir", "Voice_BR_Sleipnir"),
    "express76": ("Express76", "Voice_PECS_Express76"),
    "constantia": ("ConstantiaS2", "Voice_3P_ConstantiaS2"),
    "lrl": ("LRL", "Voice_PECS_LRL"),
    "labiata": ("Labiata", "Voice_3P_Labiata"),
    "peregrinus": ("Peregrinus", "Voice_PECS_Peregrinus"),
    # Hidden pilot: CT66 Rampart in its custom-pack skin (NS1 voice set).
    "rampalion": ("RampartNS1", "Voice_AGS_Rampart_NS1"),
}
# Extra per-pilot moments: Rampalion's C by level (special1..3 = SpSkill_4 / _3 / _2, the
# custom pack's own skill shouts), played instead of `special` when present (js/game.js).
EXTRA_SLOTS = {"rampalion": {"special1": "SpSkill_4", "special2": "SpSkill_3", "special3": "SpSkill_2"}}
SLOTS = {"sortie": "SortiePick", "stageStart": "StageStart", "special": "ActionApprove", "bomb": "SpSkill",
         "warning": "BattleFocus", "miss": "Retreat", "gameover": "Retire", "clear": "MVP"}


# Pilots whose lines go through the soft-limited chain (tools/import-rampalion-sfx.py fit):
# a peaky line still reaches the -15 dB target instead of stopping under the peak ceiling.
LIMITED = {"rampalion"}


def _fit():
    import importlib.util
    spec = importlib.util.spec_from_file_location("irs", Path(__file__).resolve().parent / "import-rampalion-sfx.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.fit


def find(folder, prefix, slot):
    d = SRC / folder
    if prefix:
        f = d / f"{prefix}_{slot}.mp3"
        if f.exists():
            return f
    hits = sorted(p for p in d.glob(f"*_{slot}.mp3"))
    return hits[0] if hits else None


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    table = {}
    for key, (folder, prefix) in PILOTS.items():
        table[key] = {}
        for slot, name in {**SLOTS, **EXTRA_SLOTS.get(key, {})}.items():
            src = find(folder, prefix, name)
            if not src:
                print("  missing", key, name)
                continue
            if key in LIMITED:
                x = _fit()(decode(src), TARGET)
                stem = f"{key}_{slot}"
                subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "-",
                                "-c:a", "libvorbis", "-q:a", "4", str(OUT / f"{stem}.ogg")],
                               input=x.astype(np.float32).tobytes(), check=True)
                table[key][slot] = stem
                print(f"{stem:24} <- {src.name:44} {len(x) / SR:.2f}s (limited)")
                continue
            x = decode(src)
            m = measure(x)
            x = x[int(m["lead"] * SR):].copy()
            x[:64] *= np.linspace(0, 1, min(64, len(x)), dtype=np.float32)
            m2 = measure(x)
            gain = 10 ** ((TARGET - m2["rms_db"]) / 20)
            peak = float(np.max(np.abs(x))) * gain
            if peak > 10 ** (-1.5 / 20):
                gain *= 10 ** (-1.5 / 20) / peak
            stem = f"{key}_{slot}"
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "-",
                            "-c:a", "libvorbis", "-q:a", "4", str(OUT / f"{stem}.ogg")],
                           input=(x * gain).astype(np.float32).tobytes(), check=True)
            table[key][slot] = stem
            print(f"{stem:24} <- {src.name:44} {len(x) / SR:.2f}s")
    with open(ROOT / "js" / "pilot-voices.js", "w", encoding="utf-8") as f:
        f.write("// Generated by tools/import-pilot-voices.py. Do not edit.\n")
        f.write("// Original pilot battle voice lines (assets/audio/voice/<stem>.ogg) per game moment.\n")
        f.write("export const PILOT_VOICES = " + json.dumps(table, ensure_ascii=False, indent=1) + ";\n")


if __name__ == "__main__":
    main()
