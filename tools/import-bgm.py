"""Original BGM tracks -> assets/audio/bgm/<stem>.ogg + js/bgm-tracks.js.

Source: E:/LAO/Google_QA/Assets/AssetBundleResource/Sounds/BGM. The original binds BGM to
maps (BG/*.prefab _audioClip) and to characters only through their named theme songs
(TrackN_<song>_<character>); there is no per-boss table. So:
  stages 1-5      -> the five numbered battle tracks (BGM_Battle_01..05, used by the
                     original's battle maps)
  midbosses       -> the original's boss-battle tracks, one each
  stage bosses    -> the boss's own theme song when the original has one (CS Perrault,
                     Black Lilith), else a boss-battle track
  pilots          -> their own theme song (Griffon, Sleipnir, Labiata); pilots without one
                     in the original fall back to the original lobby BGM
  title / select  -> BGM_Title / BGM_Thrill_01 (sortie prep)
  game over       -> BGM_Sad_Story_01 (a cleared run keeps the pilot theme)
usage: python tools/import-bgm.py [--force]
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path("E:/LAO/Google_QA/Assets/AssetBundleResource/Sounds/BGM")
OUT = ROOT / "assets" / "audio" / "bgm"

TRACKS = {  # stem -> original file
    "title": "01 BGM_Title.mp3",
    "lobby": "02 BGM_Lobby.mp3",
    "battle_01": "03 BGM_Battle_01.mp3",
    "battle_02": "05 BGM_Battle_02.mp3",
    "battle_03": "12 BGM_Battle_03.mp3",
    "battle_04": "22 BGM_Battle_04.mp3",
    "battle_05": "30 BGM_Battle_05.mp3",
    "boss_01": "04 BGM_Battle_Boss_01.mp3",
    "boss_02": "06 BGM_Battle_Boss_02.mp3",
    "boss_03": "31 BGM_Battle_Boss_03.mp3",
    "boss_beta": "57 BGM_Boss_Beta.mp3",
    "boss_gamma": "72 BGM_Gamma_Boss.mp3",
    "boss_zeta": "73 BGM_Zeta Boss.mp3",
    "boss_10stage": "51 BGM_Battle_Boss_10Stage.mp3",
    "stronghold_march": "54 BGM_Stronghold_March.mp3",
    "theme_csperrault": "Track19_ParfaitLOVE_CSPerrault.mp3",
    "theme_blacklilith": "Track25_Overdose_BlackLilith.mp3",
    "theme_griffon": "Track6_LoverLover_Griffon.mp3",
    "theme_sleipnir": "Track9_LoverLover_Sleipnir.mp3",
    "theme_labiata": "Track32_Dawn_Labiata.mp3",
    "thrill_01": "21 BGM_Thrill_01.mp3",
    "sad_story_01": "75 BGM_Sad_Story_01.mp3",
    "tension_02": "68 BGM_tension02.mp3",
}

TABLE = {
    "title": "title",
    "select": "thrill_01",      # sortie prep (character select), one track for every pilot
    "gameover": "sad_story_01",  # game over result
    "stages": ["battle_01", "battle_02", "battle_03", "battle_04", "battle_05"],
    "leaders": {
        "mid_triton": "boss_01", "mid_nidhogg": "boss_02", "mid_glacias": "boss_03",
        "mid_goltarion": "boss_beta", "mid_satgat": "boss_gamma",
        "boss_hachiko": "stronghold_march",       # the wall's guardian: Stronghold March
        "boss_csperrault": "tension_02",          # boss fight tension (user: her idol song did not fit)
        "boss_snowfeather": "boss_zeta",
        "boss_blacklilith": "theme_blacklilith",  # her own theme (Overdose)
        "final_yimir": "boss_10stage",            # the original's final-stage boss track
    },
    "pilots": {
        "griffin": "theme_griffon", "sleipnir": "theme_sleipnir", "labiata": "theme_labiata",
        # no theme song in the original -> lobby BGM
        "express76": "lobby", "constantia": "lobby", "lrl": "lobby", "peregrinus": "lobby",
    },
}


FORCE = "--force" in sys.argv


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    for stem, name in TRACKS.items():
        src = SRC / name
        dst = OUT / f"{stem}.ogg"
        if FORCE or not dst.exists():
            # EBU R128 loudness match (-16 LUFS, true peak -1.5 dB): battle tracks and the vocal
            # character themes differ by up to 13 dB in the original files; the SFX mix
            # (tools/score-sfx.mjs balance) assumes one music level.
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(src), "-vn",
                            "-af", "loudnorm=I=-16:LRA=11:TP=-1.5", "-ar", "44100",
                            "-c:a", "libvorbis", "-q:a", "3", str(dst)], check=True)
        total += dst.stat().st_size
        print(f"{stem:18} <- {name}  {dst.stat().st_size / 1048576:.1f}MB")
    with open(ROOT / "js" / "bgm-tracks.js", "w", encoding="utf-8") as f:
        f.write("// Generated by tools/import-bgm.py. Do not edit.\n")
        f.write("// Original LAO BGM (assets/audio/bgm/<stem>.ogg): stage / leader / pilot theme table.\n")
        f.write("export const BGM_SOURCES = " + json.dumps(TRACKS, ensure_ascii=False) + ";\n")
        f.write("export const BGM_TABLE = " + json.dumps(TABLE, ensure_ascii=False, indent=1) + ";\n")
    print(f"total {total / 1048576:.1f}MB")


if __name__ == "__main__":
    main()
