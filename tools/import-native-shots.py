"""Copy original Unity textures byte-for-byte; no generated or reconstructed art."""
from pathlib import Path
import hashlib, json, shutil
from PIL import Image

ROOT = Path(r'E:\LAO\Google_QA\Assets')
OUT = Path(__file__).resolve().parents[1] / 'assets/native-shots'
FILES = {
 'hirume': ('AssetBundleResourceSub/FX/sqns_fx/Hirume_fire.png', [3,3], 'Hirume fire sheet'),
 'constantia': ('AssetBundleResourceSub/FX/Texture/bullet_sr_re.png', [1,1], 'Constantia_bullet.prefab'),
 'lrl': ('AssetBundleResourceSub/FX/sqns_fx/blade_Johanna.PNG', [4,3], 'Shared Unity blade sheet; also referenced by Labiata_skill1_blade1.prefab'),
 'merlin': ('AssetBundleResource/FX/character_prefab/merlin_skill/skill1/merlin_missile.png', [1,1], 'merlin_N_bullet.prefab'),
 'griffin': ('AssetBundleResourceSub/FX/sqns_fx/pani_fire_sqns_43_re.png', [3,3], 'PA00EL_skill_1_fire.prefab pani_fire_sqns_43_m (Skill1 cannon_Fire)'),
 'fafnir': ('AssetBundleResource/FX/character_prefab/fafnir_skill/Hussar_lightning1 1.png', [4,2], 'fafnir_N_Skill1_A.prefab'),
 'eternity': ('AssetBundleResourceSub/FX/Texture/gigantes_bullet_re.png', [1,1], 'Eternity_skill1_bullet.prefab'),
 'labiata': ('AssetBundleResourceSub/FX/sqns_fx/Labiata_skill2_blade2_deco.PNG', [3,3], 'Labiata_skill1_blade1.prefab'),
 'emily': ('AssetBundleResourceSub/FX/sqns_fx/lazer_sqsn.PNG', [4,4], 'lazer_beam_emily.prefab'),
}
OUT.mkdir(parents=True, exist_ok=True)
manifest = {}
frames = {}
for key,(relative,grid,usage) in FILES.items():
    source=ROOT/relative; dest=OUT/(key+'.png')
    shutil.copyfile(source,dest)
    manifest[key]={'source':str(source),'usedBy':usage,'grid':grid,
      'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'bytes':dest.stat().st_size}
    image=Image.open(source).convert('RGBA'); fw=image.width/grid[0]; fh=image.height/grid[1]
    rects=[]
    for row in range(grid[1]):
        for col in range(grid[0]):
            x,y=round(col*fw),round(row*fh)
            tile=image.crop((x,y,round((col+1)*fw),round((row+1)*fh)))
            box=tile.getchannel('A').point(lambda a: 255 if a>12 else 0).getbbox()
            if box: rects.append([x+box[0],y+box[1],box[2]-box[0],box[3]-box[1]])
    frames[key]=rects
(OUT/'sources.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf8')
(OUT.parents[1]/'js/native-shot-data.js').write_text(
    '// Generated by tools/import-native-shots.py: original sheet content bounds.\nexport const NATIVE_SHOT_FRAMES = '+json.dumps(frames)+';\n',encoding='utf8')
print(f'Copied {len(manifest)} original textures, {sum(m["bytes"] for m in manifest.values()):,} bytes')
