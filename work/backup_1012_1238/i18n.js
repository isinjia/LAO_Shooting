/**
 * UI language tables. Gameplay systems (patterns, stage plans, cheats) stay untouched.
 * Default locale is Korean (`ko`).
 */

export const LOCALES = [
  { id: 'ko', native: '한국어' },
  { id: 'ja', native: '日本語' },
  { id: 'en', native: 'English' },
  { id: 'zh-Hant', native: '繁體中文' },
  { id: 'zh-Hans', native: '简体中文' },
  { id: 'pt', native: 'Português' },
  { id: 'es', native: 'Español' },
  { id: 'ru', native: 'Русский' },
];

export const DEFAULT_LOCALE = 'ko';

const LOCALE_IDS = new Set(LOCALES.map((l) => l.id));

const HTML_LANG = {
  ko: 'ko',
  ja: 'ja',
  en: 'en',
  'zh-Hant': 'zh-Hant',
  'zh-Hans': 'zh-Hans',
  pt: 'pt-BR',
  es: 'es',
  ru: 'ru',
};

export function normalizeLang(raw) {
  const v = String(raw || '').trim();
  if (LOCALE_IDS.has(v)) return v;
  if (v === 'pt-BR' || v === 'pt-PT') return 'pt';
  if (v === 'zh-TW' || v === 'zh-HK' || v === 'zh-HANT') return 'zh-Hant';
  if (v === 'zh-CN' || v === 'zh' || v === 'zh-HANS') return 'zh-Hans';
  return DEFAULT_LOCALE;
}

/** @type {string} */
let current = DEFAULT_LOCALE;

export function getLocale() {
  return current;
}

export function setLocale(id) {
  current = normalizeLang(id);
  ensureLocaleFont(current);
  return current;
}

/** Extra CJK sheets — loaded only when that locale is selected (mobile first-paint). */
const LOCALE_FONT_HREF = {
  ja: 'https://fonts.googleapis.com/css2?family=Noto+Sans+JP:wght@400;500;700&display=swap',
  'zh-Hans': 'https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@400;500;700&display=swap',
  'zh-Hant': 'https://fonts.googleapis.com/css2?family=Noto+Sans+TC:wght@400;500;700&display=swap',
};

const _localeFontsLoaded = new Set(['ko', 'en', 'pt', 'es', 'ru']);

/** Inject locale-specific webfont stylesheet once. */
export function ensureLocaleFont(locale = current) {
  const id = normalizeLang(locale);
  const href = LOCALE_FONT_HREF[id];
  if (!href || _localeFontsLoaded.has(id) || typeof document === 'undefined') return;
  if (document.querySelector(`link[data-lao-font="${id}"]`)) {
    _localeFontsLoaded.add(id);
    return;
  }
  _localeFontsLoaded.add(id);
  const link = document.createElement('link');
  link.rel = 'stylesheet';
  link.href = href;
  link.setAttribute('data-lao-font', id);
  document.head.appendChild(link);
}

function interpolate(s, vars) {
  if (!vars) return s;
  return String(s).replace(/\{(\w+)\}/g, (_, k) => (
    vars[k] != null ? String(vars[k]) : `{${k}}`
  ));
}

export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.ko;
  const s = table[key] ?? STRINGS.ko[key] ?? key;
  return interpolate(s, vars);
}

export function charDisplayName(key, fallback = '') {
  if (!key) return fallback || '';
  const hit = STRINGS[current]?.[`char.${key}`] ?? STRINGS.ko[`char.${key}`];
  return hit || fallback || key;
}

export function kitText(charKey, part) {
  const k = `kit.${charKey}.${part}`;
  return t(k);
}

export function specialDisplayName(charKey) {
  return t(`special.${charKey}`);
}

export function rareTagline(charKey) {
  return t(`rare.${charKey}.tag`);
}

export function applyDocumentLang() {
  const loc = getLocale();
  ensureLocaleFont(loc);
  if (document.documentElement) document.documentElement.lang = HTML_LANG[loc] || loc;
  document.title = t('doc.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
}

/** Missing-key audit: every locale must contain the same keys as `ko`. */
export function missingI18nKeys() {
  const base = Object.keys(STRINGS.ko).sort();
  const report = {};
  for (const loc of Object.keys(STRINGS)) {
    if (loc === 'ko') continue;
    const have = new Set(Object.keys(STRINGS[loc] || {}));
    const missing = base.filter((k) => !have.has(k));
    const extra = Object.keys(STRINGS[loc] || {}).filter((k) => !STRINGS.ko[k]);
    if (missing.length || extra.length) report[loc] = { missing, extra };
  }
  return report;
}

