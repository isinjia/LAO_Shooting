import { chromium } from 'playwright';
const out = process.argv[2];
const browser = await chromium.launch();
const ctx = await browser.newContext({ locale: 'ko-KR', viewport: { width: 1280, height: 720 } });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(String(e))); page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 160)); });
await page.addInitScript(() => { localStorage.setItem('lao_mini_settings_v1', JSON.stringify({ v: 2, muted: true })); localStorage.setItem('lao_mini_tutorial_seen', '1'); });
await page.goto('http://localhost:5188/?cb=rs' + Date.now());
await page.waitForSelector('#btn-start', { state: 'visible', timeout: 300000 });
await page.click('#btn-start'); await page.waitForSelector('.char-card'); await page.waitForTimeout(300);
await page.evaluate(() => window.__LAO__.applySelectCheat('rampalion')); await page.waitForTimeout(4000);
await page.keyboard.press('Space');
await page.waitForFunction(() => document.getElementById('overlay')?.classList.contains('hidden'), null, { timeout: 300000 });
await page.waitForTimeout(6000);
const setup = await page.evaluate(() => {
  window.requestAnimationFrame = () => 0;
  const g = window.__LAO__.getGame(); const p = g.player;
  g._updateStageFlow = () => {}; g.stagePhase = 'waves'; g.stageIntro = 0; p.godMode = true;
  // enemies to hit: whatever is on screen + let the stage spawn some
  for (let i = 0; i < 300 && g.enemies.filter((e) => e.alive).length < 4; i++) g.update(1 / 60);
  p.x = 220; p.y = 300; p.sp = 999;
  const hp0 = g.enemies.reduce((a, e) => a + (e.alive ? e.hp : 0), 0);
  const ok = p.trySpecial(g.bullets);
  return { ok, state: p.anim.state, hasAttack: p.anim.hasAttack, nAttack: p.anim.clips.attack.length, nIdle: p.anim.clips.idle.length, hasS2: p.anim.hasSkill2, nS2: p.anim.clips.skill2.length, run: !!p.skillRun, hp0, n: g.enemies.filter((e) => e.alive).length };
});
console.log('special', JSON.stringify(setup));
const shoot = async (name, sec) => { await page.evaluate((sec) => { const g = window.__LAO__.getGame(); for (let i = 0; i < sec * 60; i++) { g.player.x = 220; g.player.y = 300; g.update(1 / 60); g.draw(); } }, sec); await page.screenshot({ path: `${out}_${name}.png` }); };
await shoot('c_lance', 1.3);
const r1 = await page.evaluate(() => { const g = window.__LAO__.getGame(); const p = g.player; for (let i = 0; i < 300 && p.skillRun; i++) { p.x = 220; p.y = 300; g.update(1 / 60); } return { runDone: !p.skillRun, state: p.anim.state }; });
console.log('after special', JSON.stringify(r1));
const b = await page.evaluate(() => { const g = window.__LAO__.getGame(); const p = g.player; p.bombs = 3; for (let i = 0; i < 400 && g.enemies.filter((e) => e.alive).length < 6; i++) g.update(1 / 60); g._bombQueued = true; g.update(1 / 60); return { run: !!p.skillRun, kind: p.skillRun?.kind, state: p.anim.state }; });
console.log('bomb', JSON.stringify(b));
const at = async (name, rt) => { const info = await page.evaluate((rt) => { const g = window.__LAO__.getGame(); const p = g.player; let n = 0; while (p.skillRun && p.skillRun.t < rt && n++ < 900) { p.x = 220; p.y = 300; g.update(1 / 60); g.draw(); } g.draw(); const r = p.skillRun; const q = r && r.spec.pos ? r.spec.pos(p, r, r.t) : null; return { t: r?.t, x: q?.x | 0 }; }, rt); console.log(name, JSON.stringify(info)); await page.screenshot({ path: `${out}_${name}.png` }); };
await at('a_tor', 1.2);
await at('b_pull', 2.0);
await at('c_lion', 2.75);
await at('d_merge', 3.6);
await at('e_dash', 4.0);
const r2 = await page.evaluate(() => { const g = window.__LAO__.getGame(); const p = g.player; for (let i = 0; i < 300 && p.skillRun; i++) g.update(1 / 60); return { done: !p.skillRun, state: p.anim.state }; });
console.log('after bomb', JSON.stringify(r2), errs.slice(0, 4));
await browser.close();
