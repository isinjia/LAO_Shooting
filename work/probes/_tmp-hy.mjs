import { chromium } from 'playwright';
const out = process.argv[2];
const browser = await chromium.launch();
const ctx = await browser.newContext({ locale: 'ko-KR', viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(String(e)));
await page.addInitScript(() => { localStorage.setItem('lao_mini_settings_v1', JSON.stringify({ v: 2, muted: true })); localStorage.setItem('lao_mini_tutorial_seen', '1'); });
await page.goto('http://localhost:5188/?cb=hy' + Date.now());
await page.waitForSelector('#btn-start', { state: 'visible', timeout: 300000 });
await page.click('#btn-start'); await page.waitForSelector('.char-card'); await page.waitForTimeout(300);
await page.evaluate(() => window.__LAO__.applySelectCheat('rampalion')); await page.waitForTimeout(4000);
await page.keyboard.press('Space');
await page.waitForFunction(() => document.getElementById('overlay')?.classList.contains('hidden'), null, { timeout: 300000 });
await page.waitForTimeout(6000);
const bb = await page.evaluate(async () => {
  window.requestAnimationFrame = () => 0;
  window.__rm = await import('/js/rampalion.js');
  const g = window.__LAO__.getGame(); const p = g.player;
  g._updateStageFlow = () => {}; g.stagePhase = 'waves'; g.stageIntro = 0; p.godMode = true;
  g.enemies.length = 0; g.bullets.clearEnemy();
  for (let i = 0; i < 30; i++) { p.x = 300; p.y = 330; g.update(1 / 60); } g.draw();
  const c = document.getElementById('game').getBoundingClientRect(); const k = c.width / 960;
  return { x: c.left + p.x * k, y: c.top + p.y * k };
});
const clip = { x: bb.x - 110, y: bb.y - 100, width: 220, height: 170 };
await page.screenshot({ path: out + '_0start.png', clip });
const st = await page.evaluate(() => { const g = window.__LAO__.getGame(); const p = g.player; const ok = window.__rm.rampHyperStart(p); for (let i = 0; i < 30; i++) { g.enemies.length = 0; p.x = 300; p.y = 330; g.update(1 / 60); } g.draw(); return ok; });
await page.screenshot({ path: out + '_1fly.png', clip: { x: bb.x - 260, y: bb.y - 200, width: 380, height: 280 } });
const fin = await page.evaluate(() => { const g = window.__LAO__.getGame(); const p = g.player; for (let i = 0; i < 120; i++) { g.enemies.length = 0; p.x = 300; p.y = 330; g.update(1 / 60); } g.draw(); return p._ramp.hyper; });
await page.screenshot({ path: out + '_2hyper.png', clip });
console.log(JSON.stringify({ st, fin }), errs.slice(0, 3));
await browser.close();
